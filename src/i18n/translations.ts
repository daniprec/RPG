export const translations: Record<Language, Dictionary> = { en, es };

export function translate(language: Language, key: string, values: Record<string, string | number> = {}): string {
  const template = translations[language][key] ?? translations.en[key] ?? key;
  return Object.entries(values).reduce((text, [name, value]) => text.replace(`{${name}}`, String(value)), template);
}
